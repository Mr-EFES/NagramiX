const assert = require('node:assert/strict');
const {createWatchPage, Video} = require('./youtube_watch_page_host.cjs');
const page = createWatchPage(process.argv[2]);
const {events, submit, transport} = page;
const first = page.video;
transport('play', 1);
first.setAttribute('disablepictureinpicture', '');
first.dispatchEvent(new Event('playing'));
assert.equal(events.at(-1).canUsePiP, false);
assert.equal(submit('canEnter', {requiresPlaying: true}), false);
first.removeAttribute('disablepictureinpicture');
page.observe();
assert.equal(events.at(-1).canUsePiP, true);
assert.equal(submit('canEnter', {requiresPlaying: true}), true);
first.getBoundingClientRect = () => ({width: 0, height: 0});
assert.equal(submit('canEnter'), false);
delete first.getBoundingClientRect;
function enter(request) {
    assert.equal(submit('probe', {request}), true);
    const picked = events.at(-1);
    const selection = {request, frameKey: picked.frameKey, video: picked.video};
    assert.equal(submit('enter', selection), true);
    return selection;
}
enter('restore-paused');
first.pause();
first.dispatchEvent(new Event('pause'));
assert.equal(events.at(-1).event, 'paused');
first.webkitSetPresentationMode('inline');
assert.equal(events.at(-1).restore, true);
const polled = enter('restore-without-event');
first.webkitPresentationMode = 'inline';
assert.equal(submit('status', polled), true);
assert.equal(events.at(-1).restore, true);
assert.equal(submit('status', polled), false);
submit('watchControl', {action: 'seek', revision: 2, value: 40});
first.dispatchEvent(new Event('seeked'));
assert.equal(events.at(-1).event, 'seeked');
assert.equal(events.at(-1).position, 40);
assert.equal(first.paused, true);

const selection = enter('remove-active');
page.replace(null);
assert.equal(events.at(-1).event, 'detached');
assert.equal(submit('canEnter'), false);
assert.equal(submit('probe', {request: 'stale'}), false);
const count = events.length;
first.dispatchEvent(new Event('error'));
first.dispatchEvent(new Event('seeked'));
assert.equal(events.length, count);
assert.equal(submit('status', selection), true);
assert.equal(submit('stop', selection), true);
assert.equal(events.at(-1).restore, false);
const next = new Video();
page.replace(next);
// A queued pause from initial media selection must not cancel startup.
next.dispatchEvent(new Event('pause'));
assert.equal(events.at(-1).event, 'ready');
transport('play', 3);
page.gesture('click', {target: {closest: () => true}});
next.pause();
next.dispatchEvent(new Event('pause'));
assert.equal(events.at(-1).event, 'paused');
// A pointer handler can pause before the later click is delivered.
transport('play', 5);
const pointer = {target: {closest: () => true}, detail: 1};
page.gesture('pointerdown', pointer);
next.pause();
next.dispatchEvent(new Event('pause'));
page.gesture('click', pointer);
assert.equal(events.at(-1).event, 'paused');
// Same media object may be reinserted. It must get one set of listeners.
page.replace(null);
page.replace(next);
transport('play', 6);
const beforePlay = events.length;
next.dispatchEvent(new Event('playing'));
assert.equal(events.length, beforePlay + 1);
next.pause();
next.dispatchEvent(new Event('pause'));
assert.equal(events.at(-1).event, 'paused');
// WebKit can accept an entry request before changing presentation mode.
const present = next.webkitSetPresentationMode.bind(next);
next.webkitSetPresentationMode = mode => { if (mode === 'inline') present(mode); };
const pending = enter('deferred');
assert.equal(submit('status', pending), true);
assert.equal(submit('stop', pending), true);
const beforeLateEntry = events.length;
present('picture-in-picture');
assert.equal(next.webkitPresentationMode, 'inline');
assert.equal(events.slice(beforeLateEntry).some(event => event.active || event.restore), false);
console.log('Watch page capability, DOM replacement, paused restore, stop, seek and early pause passed');
