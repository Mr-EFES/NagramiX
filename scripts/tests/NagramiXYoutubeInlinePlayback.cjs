const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const html = readFileSync(process.argv[2], 'utf8');
const inline = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0][1];
let events, tick, plays = 0;
const iframe = {contentWindow: {postMessage() {}}};
const window = {location: {}, setInterval(fn) { tick = fn; return 1; }};
const player = {getIframe: () => iframe, getDuration: () => 0, getCurrentTime: () => 0,
    getVideoLoadedFraction: () => 0, setSize() {}, playVideo() { plays++; }};
const context = vm.createContext({window, YT: {Player: function(id, options) { events = options.events; return player; }}});
vm.runInContext(inline.replace('%@', '{}'), context);
context.onYouTubeIframeAPIReady();
events.onReady({target: player});
const state = () => new URL(window.location.href).searchParams;
tick();
assert.equal(state().get('playback'), '-1');
assert.equal(state().get('ready'), 'true');
events.onAutoplayBlocked();
tick();
assert.equal(state().get('blocked'), 'true');
assert.equal(plays, 0);
context.play();
events.onStateChange({data: 1});
tick();
assert.equal(state().get('blocked'), 'false');
assert.equal(plays, 1);
window.onresize();
assert.equal(plays, 1);
