const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(process.argv[2], 'utf8');
const inline = html.match(/<script>([\s\S]*?)<\/script>/)[1];
let events, timer, state = -1;
const window = {location: {}, setInterval(fn) {timer = fn; return 1;}};
const iframe = {contentWindow: {postMessage() {}}};
const player = {getIframe: () => iframe, setSize() {}, getDuration: () => 90, getCurrentTime: () => 5,
    getVideoLoadedFraction: () => 1, getPlayerState: () => state, playVideo() {}, pauseVideo() {}};
const page = vm.createContext({window, YT: {Player: function(id, options) {events = options.events; return player;}}});
vm.runInContext(inline.replace('%@', '{}').replace('__NAGRAMIX_DOCUMENT__', 'clip1'), page);
page.onYouTubeIframeAPIReady();
events.onReady({target: player});
assert.equal(window.location.href, 'embed://onReady?document=clip1');
const reply = () => new URL(window.location.href).searchParams;
page.play(1);
timer();
assert.equal(reply().get('transport'), '1');
assert.equal(reply().get('playback'), '-1');
state = 1;
events.onStateChange({data: state});
assert.equal(reply().get('document'), 'clip1');
page.pause(2);
state = 2;
timer();
assert.equal(reply().get('transport'), '2');
assert.equal(reply().get('playback'), '2');
events.onError({data: 150});
assert.equal(reply().get('failed'), 'true');
console.log('PASS: document and command identity in official YouTube player callbacks');
